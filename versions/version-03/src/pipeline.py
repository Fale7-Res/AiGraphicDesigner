"""Diffusion Latent Decomposition & Dual-Path Typography pipeline for Version 03.

Supports latent attention map extraction and hybrid typographic export:
Path 1: Exact vector Bézier glyph outlines.
Path 2: Editable text element with matched font family and fallback.
"""
from dataclasses import dataclass, field
from pathlib import Path
import sys

